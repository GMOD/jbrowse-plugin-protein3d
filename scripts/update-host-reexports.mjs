#!/usr/bin/env node
/* global process, console */
/* eslint-disable no-console */
// Regenerate scripts/host-reexports.json: the ReExports list of EVERY host the
// bundle has to load on, not just the oldest.
//
// esbuild.mjs externalizes only paths every one of them re-exports, because the
// list moves in both directions. A path a new core adds is undefined on an old
// host -- the case the floor-only version of this file was written for. But a
// path an old core had and a new one DROPPED is undefined on the new host, and
// nothing static saw that at all: measured 2026-09-14, @jbrowse/core 4.0.0
// re-exports five renderer base classes that 5.0.0-beta.8 does not. This plugin
// imports none of them today, which is luck rather than design -- the same
// shape took out msaview and protein3d when `defaultCodonTable` left the
// `@jbrowse/core/util` barrel.
//
// Versions should track the host-compat probe's gated matrix. `latest` and
// `main` are hosted app builds rather than npm versions of @jbrowse/core, so
// name the closest published core: the prerelease cut from main.
//
// Usage: node scripts/update-host-reexports.mjs [4.0.0 4.3.0 5.0.0-beta.9]
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const versions =
  process.argv.length > 2
    ? process.argv.slice(2)
    : ['4.0.0', '4.3.0', '5.0.0-beta.9']
const out = path.join(import.meta.dirname, 'host-reexports.json')

async function reExportsOf(version) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'jbrowse-core-'))
  try {
    // npm has reported --json as an array and as an object keyed by package name
    const packed = JSON.parse(
      execFileSync(
        'npm',
        [
          'pack',
          `@jbrowse/core@${version}`,
          '--pack-destination',
          tmp,
          '--json',
        ],
        { encoding: 'utf8' },
      ),
    )
    const { filename } = Array.isArray(packed)
      ? packed[0]
      : Object.values(packed)[0]
    execFileSync('tar', ['-xzf', path.join(tmp, filename), '-C', tmp])
    const list = path.join(tmp, 'package/esm/ReExports/list.js')
    const paths = (await import(list)).default
    if (!Array.isArray(paths) || paths.length === 0) {
      throw new Error(`${list} did not export a list`)
    }
    return [...paths].sort((a, b) => a.localeCompare(b))
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true })
  }
}

const hosts = {}
for (const version of versions) {
  hosts[version] = await reExportsOf(version)
  console.log(`@jbrowse/core@${version}: ${hosts[version].length} paths`)
}

fs.writeFileSync(
  out,
  `${JSON.stringify(
    {
      comment:
        'GENERATED by scripts/update-host-reexports.mjs -- do not edit by hand',
      floor: versions[0],
      hosts,
    },
    null,
    2,
  )}\n`,
)

const common = versions.reduce(
  (acc, v) => acc.filter(p => hosts[v].includes(p)),
  hosts[versions[0]],
)
console.log(
  `Wrote ${versions.length} host(s); ${common.length} paths re-exported by all of them`,
)
